function lookup(locale: Locale, path: string): string | undefined {
  let current: unknown = messages[locale];
  for (const part of path.split(".")) {
    if (current && typeof current === "object" && part in current) {
      current = (current as Record<string, unknown>)[part];
    } else {
      return undefined;
    }
  }
  return typeof current === "string" ? current : undefined;
}

/** Translate a dot-path key, falling back to English then the key itself. */
export function translate(
  locale: Locale,
  path: string,
  vars?: Record<string, string | number>,
): string {
  let str = lookup(locale, path) ?? lookup("en", path) ?? path;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      str = str.replaceAll(`{${key}}`, String(value));
    }
  }
  return str;
}

export type Translator = (
  path: string,
  vars?: Record<string, string | number>,
) => string;
